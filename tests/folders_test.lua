local NS = {}
assert(loadfile("AzerothNotes/Data.lua"))("AzerothNotes", NS)
local D = NS.Data
local db = assert(D.Initialize({schemaVersion = 2, notes = {}}))
local note = D.Create(db, "Quest plan", "Never lose this body", 1)
note.tags = {"quest"}
local folder = assert(D.CreateFolder(db, "Quests", 2))
local people = assert(D.CreateFolder(db, "People", 2))
assert(not D.CreateFolder(db, " quests ", 2))
assert(not D.CreateFolder(db, " ", 2))
assert(not D.CreateFolder(db, "Unfiled", 2))
assert(not D.RenameFolder(db, people.id, "Quests", 2))
local id, revision = note.id, note.revision
assert(D.MoveNote(db, note, folder.id, 3))
assert(note.folderID == folder.id and note.revision == revision + 1)
assert(D.List(db, "quest")[1] == note)
assert(D.RenameFolder(db, folder.id, "Class Quests", 4).id == folder.id)
assert(note.folderID == folder.id)
assert(not D.MoveNote(db, note, "missing-folder", 5))
D.SetDeleted(db, note, true, 6)
assert(not D.MoveNote(db, note, people.id, 7))
assert(D.RemoveFolder(db, folder.id, 8))
assert(note.folderID == nil and note.deleted)
D.SetDeleted(db, note, false, 9)
assert(note.id == id and note.body == "Never lose this body" and note.tags[1] == "quest")
assert(D.CreateFolder(db, "Quests", 10).id ~= folder.id)
assert(D.FolderList(db)[1].name == "People")
local orphan = D.Initialize({schemaVersion = 2, notes = {n = {folderID = "absent", tags = {}}}})
assert(orphan.notes.n.folderID == nil and orphan.schemaVersion == 3)
print("Folders: migration, unique names, moves, rename, trash, removal and note preservation passed.")
