local NS = {}
assert(loadfile("AzerothNotes/Markdown.lua"))("AzerothNotes", NS)
local M = NS.Markdown
local function Has(text, expected) assert(text:find(expected, 1, true), expected .. " missing from " .. text) end
local html = M.Render("# Heading\n\nParagraph\ncontinued\n\n## Two\n### Three\n- item\n1. ordered\n> quote\n- [ ] todo\n- [x] done")
Has(html, "<h1>Heading</h1>")
Has(html, "<h2>Two</h2>")
Has(html, "<h3>Three</h3>")
Has(html, "<p>Paragraph continued</p>")
Has(html, "• item")
Has(html, "1. ordered")
Has(html, "› quote")
Has(html, "[ ] todo")
Has(html, "[x] done")
local dangerous = M.Render('<img src="bad"/> & |Hitem:1|hattack|h')
Has(dangerous, "&lt;img")
Has(dangerous, "&amp;")
Has(dangerous, "||Hitem")
assert(not dangerous:find('<img src=', 1, true))
local link = M.Render("[[A title <&>]]")
local hex = assert(link:match('href="note:(%x+)"'))
assert(M.Unhex(hex) == "A title <&>")
assert(not M.Unhex("z0") and not M.Unhex("0"))
local code = M.Render("`[[not a link]]` **strong** *thought*")
assert(not code:find('href=', 1, true))
Has(code, "strong")
Has(code, "thought")
Has(M.Render("#### unsupported\n| table |"), "#### unsupported")
assert(M.Render("") == "<html><body></body></html>")
Has(M.Render("# Unicode café 世界"), "café 世界")
local long = string.rep("plain text ", 10000)
assert(#M.Render(long) > #long)
print("Markdown: blocks, safe text, links, Unicode, unsupported syntax, and long notes passed.")
